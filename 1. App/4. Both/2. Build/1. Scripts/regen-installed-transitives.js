/**
 * Regenerates the `installedTransitives` snapshot inside the renderer manifest
 * (2. Frontend/1. Source/package.json) from the live node_modules tree.
 *
 * That field is documentation only — npm IGNORES it (webpack reads only
 * "dependencies"). It records every package installed in node_modules that is
 * NOT a direct dependency, with its resolved version, so the manifest shows the
 * full installed footprint at a glance. `install_frontend.ps1` runs this right
 * after `npm install`, so the snapshot can never drift. Safe to run standalone:
 *
 *   node "4. Both/2. Build/1. Scripts/regen-installed-transitives.js"
 *
 * Self-locating via __dirname, so the working directory does not matter.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const sourceDir = path.resolve(__dirname, '../../../2. Frontend/1. Source');
const manifestPath = path.join(sourceDir, 'package.json');
const nmDir = path.join(sourceDir, 'node_modules');

if (!fs.existsSync(nmDir)) {
  console.error(
    `[regen-installed-transitives] node_modules not found at ${nmDir} — run install_frontend.ps1 first.`,
  );
  process.exit(1);
}

// Preserve the manifest's existing line endings (CRLF or LF).
const raw = fs.readFileSync(manifestPath, 'utf8');
const eol = raw.includes('\r\n') ? '\r\n' : '\n';
const manifest = JSON.parse(raw);
const direct = new Set(Object.keys(manifest.dependencies || {}));

// Enumerate installed top-level packages (expanding @scopes), skip dot-dirs.
const installed = [];
for (const entry of fs.readdirSync(nmDir)) {
  if (entry.startsWith('.')) continue;
  if (entry.startsWith('@')) {
    for (const sub of fs.readdirSync(path.join(nmDir, entry))) {
      if (!sub.startsWith('.')) installed.push(`${entry}/${sub}`);
    }
  } else {
    installed.push(entry);
  }
}

// Transitives = installed minus the direct deps, sorted (scoped first, then alpha).
const transitives = installed.filter((name) => !direct.has(name)).sort();

const block = {
  _comment:
    'Snapshot of transitive deps present in node_modules but NOT directly imported by renderer ' +
    'source. Visibility only — npm IGNORES this field; it does not affect install/resolution ' +
    '(webpack reads only "dependencies"). Auto-regenerated by ' +
    '4. Both/2. Build/1. Scripts/regen-installed-transitives.js (run from install_frontend.ps1); ' +
    `last run ${new Date().toISOString().slice(0, 10)}.`,
};
for (const name of transitives) {
  const pj = path.join(nmDir, name, 'package.json');
  if (!fs.existsSync(pj)) continue; // skip stray dirs lacking a manifest
  block[name] = JSON.parse(fs.readFileSync(pj, 'utf8')).version;
}

// Replace in place (keeps the field's position — last — in the manifest).
manifest.installedTransitives = block;

const out = JSON.stringify(manifest, null, 2).replace(/\n/g, eol) + eol;
fs.writeFileSync(manifestPath, out, 'utf8');

const count = Object.keys(block).length - 1; // minus _comment
// Build-time Node script; E7_BUILD_QUIET silences routine build chatter (the node_modules
// error above always shows). See 5. Dev Only/LogControl.js header.
if (!process.env.E7_BUILD_QUIET) {
  console.log(
    `[regen-installed-transitives] wrote ${count} transitives (${direct.size} direct deps) to ${path.basename(manifestPath)}`,
  );
}
