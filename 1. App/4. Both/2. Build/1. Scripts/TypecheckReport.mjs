import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

// Report-only: `yarn typecheck:strict:report`. Runs TypeScript 7 over the same program as
// `yarn typecheck` (tsconfig.json) with checkJs on and skipLibCheck off, the errors the passing gate
// hides, and writes them to a Markdown checklist beside the other generated reports.
// Exit 0 = tsc ran and the report was written, errors or not (tsc itself exits non-zero on errors,
// which is expected). Exit 1 = tsc produced no parseable output at all, so a broken run (a missing
// binary, a crash, a bad option) cannot look clean. Nothing else is written.

const appDir = path.resolve(import.meta.dirname, '../../..');
const repoDir = path.resolve(appDir, '..');
const outFile = path.join(repoDir, '.claude/plans/TYPECHECK-REPORT.md');
const tscBin = path.join(appDir, 'node_modules/tsc7/bin/tsc');
const tscArgs = [
  '-p',
  './',
  '--noEmit',
  '--checkJs',
  '--skipLibCheck',
  'false',
  '--pretty',
  'false',
];
const regenerate = 'yarn typecheck:strict:report';

// path(line,col): error TSnnnn: message
const errorLine = /^(.+?)\((\d+),(\d+)\): error (TS\d+): (.*)$/;

const run = spawnSync(process.execPath, [tscBin, ...tscArgs], {
  cwd: appDir,
  encoding: 'utf8',
  maxBuffer: 1024 * 1024 * 1024,
});
if (run.error) {
  console.error(`tsc did not run: ${run.error.message}`);
  process.exit(1);
}

const errors = [];
for (const raw of `${run.stdout}\n${run.stderr}`.split(/\r?\n/)) {
  const match = errorLine.exec(raw);
  if (match) {
    const [, file, line, col, code, message] = match;
    errors.push({
      file: file.split(path.sep).join('/'),
      line: Number(line),
      col: Number(col),
      code,
      message,
    });
  } else if (/^\s+\S/.test(raw) && errors.length > 0) {
    // A continuation line of the previous error's message.
    errors[errors.length - 1].message += ` ${raw.trim()}`;
  }
}

if (errors.length === 0 && run.status !== 0) {
  console.error(`tsc exited ${run.status} with no parseable errors; first output:`);
  console.error(`${run.stdout}${run.stderr}`.slice(0, 2000));
  process.exit(1);
}

const countBy = (key) => {
  const counts = new Map();
  for (const e of errors) counts.set(e[key], (counts.get(e[key]) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
};
const cell = (text) => String(text).replaceAll('|', String.raw`\|`);
const byCode = countBy('code');
const byFile = countBy('file');

const out = [
  '# Typecheck report (checkJs on)',
  '',
  `Generated by \`${regenerate}\` (run from \`1. App/\`). It runs \`tsc\` 7 with \`--checkJs --skipLibCheck false\` over the \`tsconfig.json\` program. The passing gate, \`yarn typecheck\`, keeps \`checkJs\` off, so none of these fail it.`,
  '',
  `Total: ${errors.length} errors in ${byFile.length} files.`,
  '',
  '## By error code',
  '',
  '| Code | Errors |',
  '| --- | --- |',
  ...byCode.map(([code, n]) => `| ${code} | ${n} |`),
  '',
  '## By file',
  '',
  '| File | Errors |',
  '| --- | --- |',
  ...byFile.map(([file, n]) => `| ${cell(file)} | ${n} |`),
  '',
  '## Errors',
];
for (const [file] of byFile) {
  out.push('', `### ${file}`, '');
  const own = errors
    .filter((e) => e.file === file)
    .sort((a, b) => a.line - b.line || a.col - b.col);
  for (const e of own) out.push(`- ${e.line}:${e.col} ${e.code} ${e.message}`);
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${out.join('\n')}\n`);
console.log(
  `${errors.length} errors in ${byFile.length} files -> ${path.relative(repoDir, outFile)}`,
);
